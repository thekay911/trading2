    """한 모델의 진입 후 운용 규칙."""

    model: str
    target_rr: float          #: 목표 (R). 유동성 목표가 이보다 멀면 여기서 자른다.
    max_hold: int             #: M5 봉 수. 실제 판정은 `hold_minutes` 로 한다 —
